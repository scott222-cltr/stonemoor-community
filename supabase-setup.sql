create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Member' check (char_length(display_name) between 1 and 32),
  role text not null default 'member' check (role in ('member','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null default 'Member' check (char_length(display_name) between 1 and 32),
  body text not null check (char_length(body) between 1 and 800),
  created_at timestamptz not null default now()
);

create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  body text not null check (char_length(body) between 1 and 3000),
  category text not null default 'NEWS' check (char_length(category) between 1 and 24),
  author_id uuid references auth.users(id) on delete set null,
  author_name text not null default 'Stonemoor Team',
  created_at timestamptz not null default now()
);

create index if not exists messages_created_at_idx on public.messages(created_at);
create index if not exists announcements_created_at_idx on public.announcements(created_at desc);

alter table public.profiles enable row level security;
alter table public.messages enable row level security;
alter table public.announcements enable row level security;

-- Publicly visible profile names/roles; users can only update their own display name.
grant select on public.profiles to anon, authenticated;
revoke update on public.profiles from anon, authenticated;
grant update (display_name) on public.profiles to authenticated;

drop policy if exists "Profiles are viewable" on public.profiles;
create policy "Profiles are viewable" on public.profiles for select to anon, authenticated using (true);
drop policy if exists "Users can update their own display name" on public.profiles;
create policy "Users can update their own display name" on public.profiles for update to authenticated
using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

-- New users receive a profile; role is always member by default.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name, role)
  values (
    new.id,
    left(coalesce(nullif(new.raw_user_meta_data ->> 'display_name',''), split_part(new.email,'@',1), 'Member'), 32),
    'member'
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Signed-in members may read messages and create messages as themselves.
grant select, insert on public.messages to authenticated;
revoke all on public.messages from anon;
drop policy if exists "Signed-in members can read messages" on public.messages;
create policy "Signed-in members can read messages" on public.messages for select to authenticated using (true);
drop policy if exists "Members can send their own messages" on public.messages;
create policy "Members can send their own messages" on public.messages for insert to authenticated
with check ((select auth.uid()) = user_id);

-- Announcements are readable by anyone. Only admins can publish/edit/delete.
grant select on public.announcements to anon, authenticated;
grant insert, update, delete on public.announcements to authenticated;
drop policy if exists "Announcements are public" on public.announcements;
create policy "Announcements are public" on public.announcements for select to anon, authenticated using (true);

create or replace function public.is_stonemoor_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

drop policy if exists "Admins can publish announcements" on public.announcements;
create policy "Admins can publish announcements" on public.announcements for insert to authenticated
with check (public.is_stonemoor_admin() and author_id = (select auth.uid()));
drop policy if exists "Admins can edit announcements" on public.announcements;
create policy "Admins can edit announcements" on public.announcements for update to authenticated
using (public.is_stonemoor_admin()) with check (public.is_stonemoor_admin());
drop policy if exists "Admins can delete announcements" on public.announcements;
create policy "Admins can delete announcements" on public.announcements for delete to authenticated
using (public.is_stonemoor_admin());

-- Allow realtime to deliver database INSERT notifications to signed-in members.
do $$
begin
  alter publication supabase_realtime add table public.messages;
exception when duplicate_object then
  null;
when undefined_object then
  raise notice 'Publication supabase_realtime not found. Enable Realtime for public.messages in the Supabase dashboard.';
end $$;
